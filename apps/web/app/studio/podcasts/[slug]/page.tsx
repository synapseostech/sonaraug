"use client";

import Link from "next/link";
import { useParams, useRouter } from "next/navigation";
import { useMemo, useState } from "react";
import { Artwork, EmptyState } from "@kito/ui";
import { CONTENT_CATEGORIES, buildRssPreview, feedSettingsForShow, formatRssDuration } from "@kito/studio";
import {
  ActionRow,
  BackLink,
  Field,
  LinkButton,
  Notice,
  PageHead,
  Panel,
  PublicationPill,
  ReviewPill,
  StatusPill,
  TextArea,
  TextInput,
  ToggleChips,
} from "../../../../components/studio-ui.tsx";
import { objectUrlFor, registerObjectUrl, useStudio } from "../../../../lib/studio/store.tsx";

const LANGUAGES = ["English", "Luganda", "Runyankole", "Acholi", "Ateso", "Lusoga", "Swahili"] as const;

export default function ShowPage() {
  const params = useParams<{ slug: string }>();
  const slug = typeof params?.slug === "string" ? params.slug : "";
  const studio = useStudio();
  const router = useRouter();
  const show = studio.state.shows.find((entry) => entry.slug === slug);
  const [message, setMessage] = useState<string | null>(null);

  const episodes = show ? studio.episodesFor(show.id) : [];

  const rss = useMemo(() => {
    if (!show) return null;
    return buildRssPreview(feedSettingsForShow(show, studio.actor.name, show.languages[0]?.toLowerCase() === "english" ? "en-UG" : "lg-UG"), episodes);
  }, [show, episodes, studio.actor.name]);

  if (!show) {
    return (
      <EmptyState
        title="Show not found"
        description="That show does not exist in this workspace."
        action={
          <Link href="/studio/podcasts" className="kt-btn kt-btn--secondary kt-btn--sm">
            Back to shows
          </Link>
        }
      />
    );
  }

  const submit = () => {
    const result = studio.submitShowForReview(show.id);
    setMessage(result.ok ? "Submitted for review. It stays editable until a reviewer picks it up." : result.reason);
  };

  return (
    <>
      <BackLink href="/studio/podcasts">My podcasts</BackLink>

      <PageHead
        title={show.title}
        description={show.description}
        actions={
          <>
            <LinkButton href="/studio/record" variant="primary">
              Record an episode
            </LinkButton>
            <button type="button" className="kt-btn kt-btn--secondary kt-btn--sm" onClick={submit} disabled={show.reviewStatus === "pending" || show.reviewStatus === "approved"}>
              {show.reviewStatus === "approved" ? "Show approved" : show.reviewStatus === "pending" ? "In review" : "Submit show for review"}
            </button>
          </>
        }
      />

      {message ? <Notice tone={/submitted/i.test(message) ? "ok" : "warn"}>{message}</Notice> : null}
      {show.reviewStatus === "rejected" ? (
        <Notice tone="danger">
          <strong>Show rejected.</strong> Edit the metadata below and submit again — reviewers see the same fields you do.
        </Notice>
      ) : null}

      <div className="ws-cols">
        <Panel title="Show details" subtitle="These fields feed the RSS channel metadata and the listener catalogue.">
          <div className="ws-form-grid">
            <Field label="Artwork" hint="Generated by default; an image you choose stays in this browser session only.">
              <div className="ws-row" style={{ padding: 8, alignItems: "flex-start" }}>
                <div style={{ width: 64 }}>
                  {objectUrlFor(`art:show:${show.id}`) ? (
                    // eslint-disable-next-line @next/next/no-img-element
                    <img src={objectUrlFor(`art:show:${show.id}`) ?? ""} alt="" className="ws-row__art" style={{ width: 64, height: 64 }} />
                  ) : (
                    <Artwork seed={show.artworkSeed} title={show.title} />
                  )}
                </div>
                <div style={{ display: "grid", gap: 6 }}>
                  <label className="kt-btn kt-btn--secondary kt-btn--sm" style={{ cursor: "pointer", width: "fit-content" }}>
                    Choose image…
                    <input
                      type="file"
                      accept="image/*"
                      hidden
                      onChange={(event) => {
                        const file = event.target.files?.[0];
                        if (!file) return;
                        registerObjectUrl(`art:show:${show.id}`, URL.createObjectURL(file));
                        setMessage("Artwork selected for this session. It is not uploaded, and a reload restores the generated artwork.");
                      }}
                    />
                  </label>
                  <p className="ws-row__sub" style={{ margin: 0 }}>
                    {objectUrlFor(`art:show:${show.id}`)
                      ? "Custom image — session only."
                      : `Auto-generated from “${show.artworkSeed}”. No copyrighted image is used.`}
                  </p>
                </div>
              </div>
            </Field>
            <Field label="Status">
              <div className="ws-row__meta">
                <ReviewPill status={show.reviewStatus} />
                <StatusPill kind="plain" value={show.rights} />
              </div>
            </Field>
          </div>

          <Field label="Title" htmlFor="show-title">
            <TextInput id="show-title" value={show.title} onChange={(value) => studio.updateShow(show.id, { title: value })} />
          </Field>
          <Field label="Description" htmlFor="show-desc">
            <TextArea id="show-desc" value={show.description} onChange={(value) => studio.updateShow(show.id, { description: value })} rows={3} />
          </Field>
          <Field label="Categories">
            <ToggleChips
              options={CONTENT_CATEGORIES}
              selected={show.categories}
              onToggle={(value) =>
                studio.updateShow(show.id, {
                  categories: show.categories.includes(value)
                    ? show.categories.filter((entry) => entry !== value)
                    : [...show.categories, value],
                })
              }
            />
          </Field>
          <Field label="Languages">
            <ToggleChips
              options={LANGUAGES}
              selected={show.languages}
              onToggle={(value) =>
                studio.updateShow(show.id, {
                  languages: show.languages.includes(value) ? show.languages.filter((entry) => entry !== value) : [...show.languages, value],
                })
              }
            />
          </Field>
          <Field label="Hosts">
            <div className="ws-stack">
              {show.hosts.map((host) => (
                <div key={host.id} className="ws-row" style={{ padding: "8px 10px" }}>
                  <div className="ws-row__body">
                    <p className="ws-row__title">{host.name}</p>
                    <p className="ws-row__sub">{host.role}</p>
                  </div>
                  <button
                    type="button"
                    className="kt-btn kt-btn--ghost kt-btn--sm"
                    onClick={() => studio.updateShow(show.id, { hosts: show.hosts.filter((entry) => entry.id !== host.id) })}
                  >
                    Remove
                  </button>
                </div>
              ))}
              <button
                type="button"
                className="kt-btn kt-btn--secondary kt-btn--sm"
                onClick={() => studio.updateShow(show.id, { hosts: [...show.hosts, { id: `host-${Date.now()}`, name: `Co-host ${show.hosts.length + 1}`, role: "Co-host" }] })}
              >
                Add a host
              </button>
            </div>
          </Field>
        </Panel>

        <div className="ws-stack">
          <Panel title="Seasons" subtitle="Episode numbering is per show">
            <div className="ws-stack">
              {Array.from(new Set(episodes.map((episode) => episode.seasonNumber)))
                .sort((a, b) => a - b)
                .map((season) => (
                  <div key={season} className="ws-row" style={{ padding: "8px 10px" }}>
                    <div className="ws-row__body">
                      <p className="ws-row__title">Season {season}</p>
                      <p className="ws-row__sub">{episodes.filter((episode) => episode.seasonNumber === season).length} episodes</p>
                    </div>
                  </div>
                ))}
              <button
                type="button"
                className="kt-btn kt-btn--secondary kt-btn--sm"
                onClick={() => {
                  const nextSeason = (Math.max(0, ...episodes.map((episode) => episode.seasonNumber)) || 1) + 1;
                  const episode = studio.createEpisode(show.id, { seasonNumber: nextSeason, title: `Season ${nextSeason} opener` });
                  router.push(`/studio/episodes/${episode.id}`);
                }}
              >
                Start season {(Math.max(0, ...episodes.map((episode) => episode.seasonNumber)) || 1) + 1}
              </button>
            </div>
          </Panel>

          <Panel title="Publishing rules" subtitle="Enforced by the studio, not by convention">
            <ul className="ws-row__sub" style={{ margin: 0, paddingLeft: 18, lineHeight: 1.7 }}>
              <li>The show must be approved before any episode can publish.</li>
              <li>Episodes need audio, a 20+ character description and a declared rights basis.</li>
              <li>Only a reviewer or administrator can approve — never the creator.</li>
              <li>“Published” here updates local state only; nothing is hosted.</li>
            </ul>
          </Panel>
        </div>
      </div>

      <Panel
        title={`Episodes · ${episodes.length}`}
        subtitle="Open an episode to edit metadata, record audio and move it through the pipeline"
        actions={
          <button
            type="button"
            className="kt-btn kt-btn--primary kt-btn--sm"
            onClick={() => {
              const episode = studio.createEpisode(show.id);
              router.push(`/studio/episodes/${episode.id}`);
            }}
          >
            New episode
          </button>
        }
      >
        <div className="ws-stack">
          {episodes.length === 0 ? (
            <p className="ws-row__sub">No episodes yet. Create one above, then record or attach audio.</p>
          ) : null}
          {episodes.map((episode) => (
            <div key={episode.id} className="ws-row">
              <div className="ws-row__body">
                <Link href={`/studio/episodes/${episode.id}`} className="ws-row__title" style={{ textDecoration: "none" }}>
                  S{episode.seasonNumber}E{episode.number} · {episode.title}
                </Link>
                <p className="ws-row__sub">
                  {episode.durationSeconds ? formatRssDuration(episode.durationSeconds) : "No audio"} ·{" "}
                  {episode.audioSource === "none" ? "nothing attached" : episode.audioSource} · updated {episode.updatedAt.slice(0, 10)}
                </p>
              </div>
              <div className="ws-row__meta">
                <PublicationPill status={episode.publicationStatus} />
                <ReviewPill status={episode.reviewStatus} />
                <LinkButton href={`/studio/episodes/${episode.id}`}>Edit</LinkButton>
              </div>
            </div>
          ))}
        </div>
      </Panel>

      <Panel
        title="RSS preview"
        subtitle="Exactly what a hosting provider would receive — generated locally, never registered with a directory"
        actions={<StatusPill kind="plain" value={rss?.publicUrl ? "public url set" : "no public url"} />}
      >
        {rss ? (
          <>
            <div className="ws-form-grid">
              <Field label="Feed title">
                <TextInput value={rss.publicUrl ? "Ready" : show.title} onChange={() => undefined} disabled />
              </Field>
              <Field label="Episodes in feed" hint="Only episodes with audio are included.">
                <TextInput value={String(rss.itemCount)} onChange={() => undefined} disabled />
              </Field>
            </div>
            {rss.warnings.length > 0 ? (
              <Notice tone="warn">
                <strong>{rss.warnings.length} feed warnings.</strong>
                <ul style={{ margin: "6px 0 0", paddingLeft: 18 }}>
                  {rss.warnings.map((warning) => (
                    <li key={warning}>{warning}</li>
                  ))}
                </ul>
              </Notice>
            ) : (
              <Notice tone="ok">Feed is complete for the fields this build models.</Notice>
            )}
            <pre className="ws-rss" aria-label="RSS feed preview">
              {rss.xml}
            </pre>
            <ActionRow>
              <button type="button" className="kt-btn kt-btn--secondary kt-btn--sm" onClick={submit}>
                Re-submit show for review
              </button>
              <span className="ws-row__sub" style={{ alignSelf: "center" }}>
                No public feed URL is generated: hosting is not configured in this phase.
              </span>
            </ActionRow>
          </>
        ) : null}
      </Panel>
    </>
  );
}
